function translateText(value: string, language: AppLanguage): string {
  const trimmed = value.trim();
  const translated = language === 'hi' ? englishToHindi[trimmed] : trimmed;
  return translated ? value.replace(trimmed, translated) : value;
}

export function translateUiText(value: string, language: AppLanguage): string {
  return translateText(value, language);
}

type LanguageContextValue = { language: AppLanguage; toggleLanguage: () => void };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const originalText = useRef(new WeakMap<Text, string>());
  const renderedText = useRef(new WeakMap<Text, string>());
  const originalAttributes = useRef(new WeakMap<Element, Map<string, string>>());
  const renderedAttributes = useRef(new WeakMap<Element, Map<string, string>>());
  const [language, setLanguage] = useState<AppLanguage>(() => {
    try {
      return localStorage.getItem('workforces-language') === 'hi' ? 'hi' : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.lang = language;
    try { localStorage.setItem('workforces-language', language); } catch { /* Storage may be disabled. */ }

    const ignoredTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'INPUT']);
    const shouldIgnore = (node: Node) => {
      const element = node.parentElement;
      return !element || ignoredTags.has(element.tagName) || Boolean(element.closest('[data-no-translate="true"], [contenteditable="true"]'));
    };

    const translateNode = (node: Node) => {
      if (node.nodeType !== Node.TEXT_NODE || shouldIgnore(node)) return;
      const current = node.nodeValue || '';
      const previousRender = renderedText.current.get(node as Text);
      if (!originalText.current.has(node as Text) || (previousRender !== undefined && current !== previousRender)) {
        originalText.current.set(node as Text, current);
      }
      const source = originalText.current.get(node as Text) || current;
      const next = translateText(source, language);
      renderedText.current.set(node as Text, next);
      if (next !== current) node.nodeValue = next;
    };

    const translateElement = (element: Element) => {
      if (element.closest('[data-no-translate="true"]')) return;
      for (const attribute of ['placeholder', 'aria-label', 'aria-description', 'title', 'alt']) {
        const value = element.getAttribute(attribute);
        if (value) {
          let originals = originalAttributes.current.get(element);
          if (!originals) { originals = new Map(); originalAttributes.current.set(element, originals); }
          let rendered = renderedAttributes.current.get(element);
          if (!rendered) { rendered = new Map(); renderedAttributes.current.set(element, rendered); }
          const previousRender = rendered.get(attribute);
          if (!originals.has(attribute) || (previousRender !== undefined && value !== previousRender)) originals.set(attribute, value);
          const next = translateText(originals.get(attribute) || value, language);
          rendered.set(attribute, next);
          if (next !== value) element.setAttribute(attribute, next);
        }
      }
      element.childNodes.forEach(translateNode);
    };

    const scan = (root: ParentNode) => root.querySelectorAll('*').forEach(translateElement);
    scan(document.body);
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === 'characterData') translateNode(record.target);
        else if (record.type === 'attributes' && record.target instanceof Element) translateElement(record.target);
        else record.addedNodes.forEach(node => {
          if (node instanceof Element) {
            translateElement(node);
            scan(node);
          } else translateNode(node);
        });
      }
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'aria-description', 'title', 'alt'] });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(() => ({ language, toggleLanguage: () => setLanguage(current => current === 'en' ? 'hi' : 'en') }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider');
  return context;
}

export function LanguageToggle() {
  const { language, toggleLanguage } = useLanguage();
  return (
    <button
      type="button"
      className="language-toggle"
      data-no-translate="true"
      onClick={toggleLanguage}
      aria-label={language === 'en' ? 'हिंदी में बदलें' : 'Switch to English'}
      title={language === 'en' ? 'हिंदी में बदलें' : 'Switch to English'}
    >
      {language === 'en' ? 'हिंदी' : 'English'}
    </button>
  );
}
